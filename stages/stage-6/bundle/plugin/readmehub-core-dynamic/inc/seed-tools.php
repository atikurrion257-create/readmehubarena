/**
 * Find an existing rmh_tool post by its canonical slug.
 *
 * @param string $slug Tool slug.
 * @return int|null Post ID or null when missing.
 */
function rmh_find_tool_post_by_slug( string $slug ): ?int {
	$found = get_posts(
		array(
			'post_type'      => 'rmh_tool',
			'name'           => $slug,
			'post_status'    => 'any',
			'posts_per_page' => 1,
			'fields'         => 'ids',
			'no_found_rows'  => true,
		)
	);
	return ! empty( $found ) ? (int) $found[0] : null;
}

/**
 * Seed or sync all 17 canonical rmh_tool records.
 *
 * @param bool $force_overwrite Deprecated; existing metadata is never overwritten.
 * @return array{created:int, updated:int, skipped:int}
 */
function rmh_seed_all_tool_records( bool $force_overwrite = false ): array {
	rmh_seed_default_taxonomy_terms();

	$summary = array(
		'created' => 0,
		'updated' => 0,
		'skipped' => 0,
	);

	foreach ( rmh_get_canonical_tool_registry() as $record ) {
		$slug    = (string) $record['tool_slug'];
		$post_id = rmh_find_tool_post_by_slug( $slug );

		$meta = array(
			'rmh_tool_slug'              => $slug,
			'rmh_no_www_enforced'        => 'systeme-io' === $slug ? '1' : '0',
			'rmh_category'               => (string) $record['category'],
			'rmh_program_status'         => (string) $record['program_status'],
			'rmh_verification_status'    => (string) $record['verification_status'],
			'rmh_application_status'     => (string) $record['application_status'],
			'rmh_approval_status'        => (string) $record['approval_status'],
			'rmh_affiliate_url_template' => (string) $record['affiliate_url_template'],
			'rmh_commission_summary'     => (string) $record['commission_summary'],
			'rmh_cookie_days'            => empty( $record['cookie_days'] ) ? '' : (int) $record['cookie_days'],
			'rmh_cookie_note'            => (string) $record['cookie_note'],
			'rmh_minimum_payout'         => (string) $record['minimum_payout'],
			'rmh_priority'               => (string) $record['priority'],
			'rmh_wave'                   => (string) $record['wave'],
			'rmh_verified_date'          => (string) $record['verified_date'],
			'rmh_expires_date'           => (string) $record['expires_date'],
			'rmh_price_note'             => (string) $record['price_note'],
			'rmh_free_tier_note'         => (string) $record['free_tier_note'],
			'rmh_pros_list'              => (string) $record['pros_list'],
			'rmh_cons_list'              => (string) $record['cons_list'],
			'rmh_best_for'               => (string) $record['best_for'],
			'rmh_not_best_for'           => (string) $record['not_best_for'],
			'rmh_verdict'                => (string) $record['verdict'],
		);

		if ( null === $post_id ) {
			$post_id = wp_insert_post(
				array(
					'post_type'    => 'rmh_tool',
					'post_title'   => (string) $record['title'],
					'post_name'    => $slug,
					'post_status'  => 'draft',
					'post_content' => '',
				),
				true
			);
			if ( is_wp_error( $post_id ) ) {
				$summary['skipped']++;
				continue;
			}
			$summary['created']++;
		} else {
			// Reseeding must not overwrite owner-entered status, links or editorial data.
			foreach ( array_keys( $meta ) as $key ) {
				if ( metadata_exists( 'post', $post_id, $key ) ) {
					unset( $meta[ $key ] );
				}
			}
			$summary['updated']++;
		}
		// Editorial assertions and prices lack individual source verification; do not seed them.
		foreach ( array( 'rmh_price_note', 'rmh_free_tier_note', 'rmh_pros_list', 'rmh_cons_list', 'rmh_best_for', 'rmh_not_best_for', 'rmh_verdict' ) as $unverified_key ) {
			unset( $meta[ $unverified_key ] );
		}

		foreach ( $meta as $key => $value ) {
			update_post_meta( (int) $post_id, $key, $value );
		}

		if ( ! has_term( '', 'rmh_silo', (int) $post_id ) && ! empty( $record['silo'] ) && term_exists( (string) $record['silo'], 'rmh_silo' ) ) {
			wp_set_object_terms( (int) $post_id, array( (string) $record['silo'] ), 'rmh_silo', false );
		}
		if ( ! has_term( '', 'rmh_cluster', (int) $post_id ) && ! empty( $record['cluster'] ) && term_exists( (string) $record['cluster'], 'rmh_cluster' ) ) {
			wp_set_object_terms( (int) $post_id, array( (string) $record['cluster'] ), 'rmh_cluster', false );
		}
	}

	return $summary;
}
